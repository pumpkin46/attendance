"""Merge branches + departments into a self-referential organizations tree.

Hand-authored (not autogenerated). The ``organizations`` table becomes a tree:
a company *root* (``parent_id IS NULL``) is the tenant; ``branches`` and
``departments`` rows are migrated to descendant nodes. ``locations`` is kept
and repointed. Members (employees, users, locations) gain a single
``org_node_id`` replacing ``branch_id`` + ``department_id``.

Backfill precedence: department node if set, else branch node. The free-text
``employees.department`` label is left untouched. A ``_org_merge_audit`` table
preserves any branch link dropped when an employee's branch differed from its
department's branch (so the loss is recoverable post-hoc).

PostgreSQL only (like the rest of this chain — see e1f2a3b4c5d6). The data
transformation lives in ``backfill_org_tree`` using portable SQL so it can be
unit-tested against SQLite; the DDL below targets PostgreSQL.

FORWARD-ONLY: downgrade raises. branch/department identity and post-migration
reparenting cannot be losslessly reconstructed — restore from a backup instead.

Constraint name ``organizations_code_key`` assumes PostgreSQL's default naming
for the original column-level ``UNIQUE(code)`` (see 50fa64e85121).

Revision ID: g3b4c5d6e7f8
Revises: f2a3b4c5d6e7
Create Date: 2026-06-17
"""

