def _assert_zero(conn, from_where: str) -> None:
    n = conn.execute(sa.text(f"SELECT count(*) FROM {from_where}")).scalar()
    if n:
        raise RuntimeError(
            f"org-tree migration integrity check failed: {n} row(s) in {from_where}"
        )


def backfill_org_tree(conn) -> None:
    """Populate the tree columns and repoint members. Portable (PG + SQLite).

    Assumes the new columns already exist on organizations/employees/users/
    locations, the old branches/departments tables still hold data, and the
    ``_org_merge_audit`` table exists. Does no NOT-NULL/constraint DDL.
    """
    # 0a. Cross-org dept->branch corruption: detach mismatched branch links
    #     (reparent the department to its own company root instead).
    conn.execute(
        sa.text(
            """
            UPDATE departments SET branch_id = NULL
            WHERE branch_id IS NOT NULL AND branch_id IN (
                SELECT b.id FROM branches b
                WHERE b.id = departments.branch_id
                  AND b.organization_id <> departments.organization_id
            )
            """
        )
    )

    # Anchor every existing organization as a company root.
    conn.execute(
        sa.text(
            """
            UPDATE organizations
            SET root_organization_id = id,
                node_type = 'company',
                depth = 0,
                path = '/' || CAST(id AS VARCHAR) || '/'
            WHERE parent_id IS NULL
            """
        )
    )

    roots = conn.execute(
        sa.text("SELECT id, code, path FROM organizations WHERE parent_id IS NULL")
    ).fetchall()
    root_path = {r.id: r.path for r in roots}
    used_codes: dict[int, set[str]] = {}
    for r in roots:
        used_codes.setdefault(r.id, set()).add(r.code)

    def unique_code(root_id: int, base: str, node_type: str, legacy_id: int) -> str:
        seen = used_codes.setdefault(root_id, set())
        cand = base
        if cand in seen:
            cand = f"{base}-{node_type}"
        if cand in seen:
            cand = f"{base}-{node_type}-{legacy_id}"
        suffix = 0
        while cand in seen:
            suffix += 1
            cand = f"{base}-{node_type}-{legacy_id}-{suffix}"
        seen.add(cand)
        return cand

    def insert_node(root_id, parent_id, parent_path, node_type, name, code, address, timezone, is_active, depth):
        # RETURNING id captures the new row deterministically — no dependency on
        # (root, code) being unique during the backfill window (a subtle code
        # collision would otherwise let the re-select pick the wrong row).
        new_id = conn.execute(
            sa.text(
                """
                INSERT INTO organizations
                    (name, code, parent_id, root_organization_id, node_type,
                     path, depth, timezone, address, is_active)
                VALUES (:name, :code, :parent, :root, :ntype, '', :depth, :tz, :addr, :active)
                RETURNING id
                """
            ),
            {
                "name": name, "code": code, "parent": parent_id, "root": root_id,
                "ntype": node_type, "depth": depth, "tz": timezone or "UTC",
                "addr": address, "active": is_active,
            },
        ).scalar()
        path = f"{parent_path}{new_id}/"
        conn.execute(
            sa.text("UPDATE organizations SET path = :p WHERE id = :id"),
            {"p": path, "id": new_id},
        )
        return new_id, path

    # Branch nodes (depth 1, parented to the company root).
    branch_map: dict[int, tuple[int, str]] = {}
    for b in conn.execute(
        sa.text(
            "SELECT id, organization_id, name, code, address, timezone, is_active FROM branches"
        )
    ).fetchall():
        root_id = b.organization_id
        code = unique_code(root_id, b.code, "branch", b.id)
        new_id, path = insert_node(
            root_id, root_id, root_path[root_id], "branch",
            b.name, code, b.address, b.timezone, b.is_active, 1,
        )
        branch_map[b.id] = (new_id, path)

    # Department nodes (under their branch node if any, else the company root).
    dept_map: dict[int, int] = {}
    for d in conn.execute(
        sa.text(
            "SELECT id, organization_id, branch_id, name, code, is_active FROM departments"
        )
    ).fetchall():
        root_id = d.organization_id
        if d.branch_id is not None and d.branch_id in branch_map:
            parent_id, parent_path = branch_map[d.branch_id]
            depth = 2
        else:
            parent_id, parent_path, depth = root_id, root_path[root_id], 1
        code = unique_code(root_id, d.code, "department", d.id)
        new_id, _ = insert_node(
            root_id, parent_id, parent_path, "department",
            d.name, code, None, "UTC", d.is_active, depth,
        )
        dept_map[d.id] = new_id

    # Audit: preserve branch links dropped by department-wins precedence.
    for member in ("employee", "user"):
        table = "employees" if member == "employee" else "users"
        conn.execute(
            sa.text(
                f"""
                INSERT INTO _org_merge_audit (member_type, member_id, branch_id, department_id)
                SELECT '{member}', m.id, m.branch_id, m.department_id
                FROM {table} m
                LEFT JOIN departments d ON d.id = m.department_id
                WHERE m.branch_id IS NOT NULL
                  AND m.department_id IS NOT NULL
                  AND (d.branch_id IS NULL OR d.branch_id <> m.branch_id)
                """
            )
        )

    # Id maps as temp tables, for set-based repointing.
    conn.execute(sa.text("CREATE TEMPORARY TABLE _branch_map (legacy_id INTEGER PRIMARY KEY, new_id INTEGER)"))
    conn.execute(sa.text("CREATE TEMPORARY TABLE _dept_map (legacy_id INTEGER PRIMARY KEY, new_id INTEGER)"))
    if branch_map:
        conn.execute(
            sa.text("INSERT INTO _branch_map (legacy_id, new_id) VALUES (:l, :n)"),
            [{"l": k, "n": v[0]} for k, v in branch_map.items()],
        )
    if dept_map:
        conn.execute(
            sa.text("INSERT INTO _dept_map (legacy_id, new_id) VALUES (:l, :n)"),
            [{"l": k, "n": v} for k, v in dept_map.items()],
        )

    # Repoint members: department wins, else branch.
    for table in ("employees", "users"):
        conn.execute(
            sa.text(
                f"""
                UPDATE {table} SET org_node_id =
                    (SELECT new_id FROM _dept_map WHERE legacy_id = {table}.department_id)
                WHERE department_id IS NOT NULL
                """
            )
        )
        conn.execute(
            sa.text(
                f"""
                UPDATE {table} SET org_node_id =
                    (SELECT new_id FROM _branch_map WHERE legacy_id = {table}.branch_id)
                WHERE org_node_id IS NULL AND branch_id IS NOT NULL
                """
            )
        )
    # Root-less guard: a user with no tenant must not carry a scope node.
    conn.execute(sa.text("UPDATE users SET org_node_id = NULL WHERE organization_id IS NULL"))

    # Locations only ever pointed at a branch.
    conn.execute(
        sa.text(
            """
            UPDATE locations SET org_node_id =
                (SELECT new_id FROM _branch_map WHERE legacy_id = locations.branch_id)
            WHERE branch_id IS NOT NULL
            """
        )
    )

    conn.execute(sa.text("DROP TABLE _branch_map"))
    conn.execute(sa.text("DROP TABLE _dept_map"))


